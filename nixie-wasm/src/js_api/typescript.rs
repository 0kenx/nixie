/// Generate the full TypeScript `.d.ts` content for the Nixie WASM JS API.
///
/// The returned string is the complete content ready to be written to
/// `nixie-wasm/typescript/nixie.d.ts`.
///
/// # Example
///
/// ```rust
/// use nixie_wasm::js_api::typescript::generate_typescript_dts;
///
/// let dts = generate_typescript_dts();
/// assert!(dts.contains("NixieSolver"));
/// assert!(dts.contains("SolverResult"));
/// assert!(dts.contains("SolverConfig"));
/// assert!(dts.contains("ModelValue"));
/// assert!(dts.contains("solve("));
/// assert!(dts.contains("version("));
/// assert!(dts.contains("class CancellationToken"));
/// assert!(dts.contains("class PreemptibleSolver"));
/// ```
pub fn generate_typescript_dts() -> String {
    let mut out = String::with_capacity(8 * 1024);

    out.push_str(DTS_HEADER);
    out.push_str(DTS_SOLVER_RESULT);
    out.push_str(DTS_MODEL_VALUE);
    out.push_str(DTS_SOLVER_CONFIG);
    out.push_str(DTS_NIXIE_SOLVER);
    out.push_str(DTS_SOLVE_FN);
    out.push_str(DTS_PREEMPTIBLE_WORKER);
    out.push_str(DTS_VERSION_FN);

    out
}

