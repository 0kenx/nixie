//! TypeScript type-definition generator for the Nixie WASM JS API.
//!
//! `generate_typescript_dts()` returns the full content of the hand-maintained
//! `nixie.d.ts` file as a `String`.  Embedding the definitions here means the
//! Rust source is always the single source of truth – any downstream tooling
//! can call this function and write the result to disk instead of maintaining
//! a parallel file by hand.
//!
//! # Covered types
//!
//! | TypeScript entity  | Description                                        |
//! |--------------------|----------------------------------------------------|
//! | `SolverResult`     | Return value of `check()` / `solve()`              |
//! | `ModelValue`       | A single variable assignment in a satisfying model |
//! | `SolverConfig`     | Constructor options for `NixieSolver`               |
//! | `NixieSolver`       | Main solver class (mirrors `WasmSolver`)           |
//! | `solve()`          | Convenience one-shot function                      |
//! | `version()`        | Returns the package version string                 |
//! | `CancellationToken`| Cooperative cancellation flag (local or shared)    |
//! | `PreemptibleSolver`| Runs a solve in a `Worker`; HARD-kills on timeout  |

