#[test]
fn shrink_block_uip_trail_index_zero_is_not_unsat() {
    assert!(brute_force_is_sat(8), "oracle: the instance is satisfiable");
    let mut solver = Solver::new();
    for _ in 0..8 {
        solver.new_var();
    }
    for clause in BLOCKS {
        let lits: Vec<Lit> = clause
            .iter()
            .map(|&l| {
                let var = Var::new(l.unsigned_abs() - 1);
                if l > 0 { Lit::pos(var) } else { Lit::neg(var) }
            })
            .collect();
        assert!(
            solver.add_clause(lits),
            "clause {clause:?} is not trivially unsat"
        );
    }
    assert_eq!(
        solver.solve(),
        SolverResult::Sat,
        "block-UIP shrinking must not refute a satisfiable instance"
    );
}

/// Exhaustive oracle: some assignment satisfies every clause.
fn brute_force_is_sat(num_vars: usize) -> bool {
    (0u32..(1u32 << num_vars)).any(|mask| {
        BLOCKS.iter().all(|clause| {
            clause.iter().any(|&lit| {
                let var_bit = (mask >> (lit.unsigned_abs() as usize - 1)) & 1 == 1;
                (lit > 0) == var_bit
            })
        })
    })
}
